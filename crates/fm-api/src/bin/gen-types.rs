//! Writes the TypeScript types for the desktop UI.
//!
//! Run through `pnpm gen:types`. CI regenerates the file and fails when the
//! committed copy differs, so the UI and the API cannot drift.

use std::path::PathBuf;
use std::process::ExitCode;

fn main() -> ExitCode {
    let out = std::env::args()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("apps/desktop/src/api/types.ts"));
    match fm_api_types::write(&out) {
        Ok(()) => {
            println!("wrote {}", out.display());
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("gen-types: {e}");
            ExitCode::FAILURE
        }
    }
}

mod fm_api_types {
    use std::path::Path;

    use specta::Types;
    use specta_typescript::Typescript;

    pub fn write(out: &Path) -> Result<(), String> {
        let types = Types::default().register::<fm_api::ApiVersion>();
        let body = Typescript::default()
            .header("// Generated by `pnpm gen:types` from crates/fm-api. Do not edit.\n")
            .export(&types, specta_serde::Format)
            .map_err(|e| e.to_string())?;
        let version = fm_api::API_VERSION;
        let text = format!(
            "{body}\nexport const API_VERSION: ApiVersion = {{ major: {}, minor: {}, patch: {} }};\n",
            version.major, version.minor, version.patch
        );
        if let Some(dir) = out.parent() {
            std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
        }
        std::fs::write(out, text).map_err(|e| format!("{}: {e}", out.display()))
    }
}
